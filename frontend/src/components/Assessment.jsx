import React, { useState } from "react";
import { api } from "../api";
import { STAGES, pct, priorityClass, toNumberOrNull } from "../fields";
import StageInputs from "./StageInputs";
import { DeclinePanel, PathwayTrace, QualityPanel, ShapChart, UncertaintyPanel } from "./ResultViews";

const EMPTY = {
  patient_ref: "",
  sex: "2",
  age: "",
  education: "",
  mmse: "",
  adas: "",
  faq: "",
  moca: "",
  cdr: "",
};

const NUMERIC_KEYS = [
  "age", "education", "mmse", "adas", "faq", "sex", "moca", "cdr",
  "bmi", "sbp", "gds", "hx_cardiovascular", "hx_endocrine", "hx_psychiatric",
  "hx_neurologic", "hx_smoking",
  "ptau217", "ab42_ab40", "nfl", "gfap", "ptau181", "nfl_legacy", "apoe4",
  "eTIV", "nWBV", "ASF", "hippocampus_icv",
  "amyloid_centiloid", "fdg",
];

export default function Assessment({ modelInfo }) {
  const [form, setForm] = useState(EMPTY);
  const [openStages, setOpenStages] = useState({ stage2: false, stage3: false, stage4: false });
  const [result, setResult] = useState(null);
  const [uncertainty, setUncertainty] = useState(null);
  const [error, setError] = useState("");
  const [loading, setLoading] = useState(false);

  const available = new Set(modelInfo?.available_stages || []);
  const update = (key, value) => setForm((previous) => ({ ...previous, [key]: value }));

  const submit = async (event) => {
    event.preventDefault();
    setError("");
    setResult(null);
    setUncertainty(null);
    setLoading(true);

    // A new assessment ID is generated by the server for every submission.
    const payload = { patient_ref: form.patient_ref.trim() || "anonymous" };
    for (const key of NUMERIC_KEYS) payload[key] = toNumberOrNull(form[key]);

    try {
      const data = await api("/assessment", { method: "POST", body: payload });
      setResult(data);
      api("/uncertainty", { method: "POST", body: { ...payload, stage: "stage1" } })
        .then(setUncertainty)
        .catch((err) => setUncertainty({ available: false, reason: err.message }));
    } catch (err) {
      setError(err.message);
    } finally {
      setLoading(false);
    }
  };

  return (
    <>
      <section className="card">
        <div className="section-heading">
          <div>
            <span className="section-number">01</span>
            <h2>Patient Assessment</h2>
          </div>
          <span className="stage-tag">PROGRESSIVE PATHWAY</span>
        </div>
        <div className="intro-row">
          <p className="section-description">
            Enter Stage-1 screening results. If the patient already has blood
            biomarker, MRI or PET results, open that stage and add them. The
            deepest stage with results and a trained model determines the
            priority tier.
          </p>
          <img className="section-illustration" src="/images/patient-gears.webp" alt="" />
        </div>

        {error && <div className="alert error"><strong>Error:</strong> {error}</div>}

        <form onSubmit={submit}>
          <div className="assessment-grid">
            <label>
              Patient reference
              <span className="input-help">Pseudonymous ID, no names</span>
              <input
                value={form.patient_ref}
                onChange={(e) => update("patient_ref", e.target.value)}
                placeholder="e.g. patient-001"
                maxLength={100}
              />
            </label>
            <label>
              Sex
              <span className="input-help">ADNI coding</span>
              <select value={form.sex} onChange={(e) => update("sex", e.target.value)}>
                <option value="1">Male</option>
                <option value="2">Female</option>
              </select>
            </label>
            <label>
              MoCA
              <span className="input-help">Contextual only, not a model input</span>
              <input type="number" min="0" max="30" step="1" value={form.moca}
                onChange={(e) => update("moca", e.target.value)} placeholder="Optional" />
            </label>
            <label>
              CDR global
              <span className="input-help">Routing only (CDR 0 → early detection)</span>
              <select value={form.cdr} onChange={(e) => update("cdr", e.target.value)}>
                <option value="">Not recorded</option>
                <option value="0">0</option>
                <option value="0.5">0.5</option>
                <option value="1">1</option>
                <option value="2">2</option>
                <option value="3">3</option>
              </select>
            </label>
          </div>

          <StageInputs stage="stage1" values={form} onChange={update} available={available.has("stage1")} />

          {STAGES.slice(1).map((stage) => (
            <div key={stage}>
              <button
                type="button"
                className="link-button"
                onClick={() => setOpenStages((s) => ({ ...s, [stage]: !s[stage] }))}
              >
                {openStages[stage] ? "−" : "+"} {stage === "stage2" ? "Add blood biomarker results"
                  : stage === "stage3" ? "Add MRI results" : "Add PET results"}
              </button>
              {openStages[stage] && (
                <StageInputs stage={stage} values={form} onChange={update} available={available.has(stage)} />
              )}
            </div>
          ))}

          <div className="form-actions">
            <button type="submit" className="primary-button" disabled={loading}>
              {loading ? "Calculating..." : "Calculate & add to queue"}
            </button>
            <button type="button" className="secondary-button" onClick={() => { setForm(EMPTY); setResult(null); }}>
              Clear form
            </button>
          </div>
        </form>
      </section>

      {result && (
        <>
          <section className="card result-card">
            <div className="section-heading">
              <div>
                <span className="section-number">02</span>
                <h2>Prioritization Result</h2>
              </div>
              <span className="stage-tag">{result.task.replace("_", " ")}</span>
            </div>

            <div className="result-grid">
              <div className="risk-panel">
                <span className="metric-label">CALIBRATED RESEARCH RISK · {result.prediction.current_stage_name}</span>
                <div className="risk-value">{pct(result.prediction.risk_score)}</div>
                <div className={`priority-badge ${priorityClass(result.prediction.priority)}`}>
                  {result.prediction.priority} PRIORITY
                </div>
                <p className="metric-note">
                  Model-estimated 24-month progression risk score, not a
                  diagnosis or clinical probability of Alzheimer's disease.
                </p>
              </div>
              <QualityPanel quality={result.data_quality} />
            </div>

            <h3>Diagnostic pathway</h3>
            <PathwayTrace trace={result.pathway.trace} nextStep={result.pathway.next_step} />

            <div className="result-meta">
              <div><span>Assessment</span><strong>{result.assessment_id}</strong></div>
              <div><span>Model</span><strong>{result.prediction.model_version}</strong></div>
              <div><span>Queue</span><strong>Saved to prioritization queue</strong></div>
            </div>
          </section>

          <section className="card">
            <div className="section-heading">
              <div>
                <span className="section-number">03</span>
                <h2>Why this score? (SHAP)</h2>
              </div>
            </div>
            <ShapChart explanation={result.explanation} />
          </section>

          <section className="card">
            <div className="section-heading">
              <div>
                <span className="section-number">04</span>
                <h2>How fast? Expected decline (TEMPO)</h2>
              </div>
              <span className="stage-tag">36-MONTH RATE</span>
            </div>
            <DeclinePanel decline={result.decline} priority={result.prediction.priority} />
            {result.decline?.explanation && (
              <>
                <h3>Why this rate? (SHAP)</h3>
                <ShapChart explanation={result.decline.explanation} />
              </>
            )}
          </section>

          <section className="card">
            <div className="section-heading">
              <div>
                <span className="section-number">05</span>
                <h2>Uncertainty Analysis</h2>
              </div>
            </div>
            {uncertainty ? <UncertaintyPanel uncertainty={uncertainty} /> : <p>Loading...</p>}
          </section>
        </>
      )}
    </>
  );
}
